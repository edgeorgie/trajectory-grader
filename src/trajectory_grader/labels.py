"""Human label records for the gold set, and loading them from disk.

The gold set is the one part of this project that an automated process must
NOT produce: its whole purpose is to be an independent reference that the
rubric (and, later, an LLM judge) is measured *against*. If labels were
generated by the same kind of system under evaluation, the agreement number
would measure self-consistency, not correctness.

So this module deliberately provides no label *inference* — only a schema,
a loader, and validation. Producing the verdicts is a human step.

A label file is one JSON document per trajectory:

    {
      "task_id": "triage-desk-issue24",
      "labeled_by": "edgeorgie",
      "labeled_at": "2026-10-11",
      "notes": "optional free text on why",
      "verdicts": {
        "redundant_call_after_success": "violation",
        "no_terminal_action": "ok"
      }
    }

A verdict is recorded per *rule name*, matching the rubric's rule names, so
agreement can be reported per rule rather than only in aggregate — a judge
that is excellent on one rule and useless on another is the interesting
case, and a single blended number hides it.
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any

#: A human verdict for one rule on one trajectory.
#:
#: ``ok``        — the rule's concern is genuinely absent from this trajectory.
#: ``violation`` — the rule's concern is genuinely present.
#: ``unclear``   — the labeler could not decide. Kept as a first-class value
#:                 rather than being forced into ok/violation, because
#:                 quietly coercing a genuine judgement call into a verdict
#:                 is how a gold set stops being trustworthy. Excluded from
#:                 agreement scoring (see ``agreement.py``).
VERDICTS = frozenset({"ok", "violation", "unclear"})

SCORABLE_VERDICTS = frozenset({"ok", "violation"})


@dataclass(frozen=True)
class GoldLabel:
    """One human-labeled trajectory: per-rule verdicts plus provenance.

    ``labeled_by`` / ``labeled_at`` are required, not optional: a gold label
    with no attributable author or date cannot be audited later, and an
    unauditable reference set is worth less than none.
    """

    task_id: str
    labeled_by: str
    labeled_at: str
    verdicts: dict[str, str]
    notes: str | None = None

    def __post_init__(self) -> None:
        if not self.task_id:
            raise ValueError("a gold label must name the task_id it labels")
        if not self.labeled_by:
            raise ValueError(f"{self.task_id}: labeled_by is required (who made this judgement)")
        if not self.labeled_at:
            raise ValueError(f"{self.task_id}: labeled_at is required (when it was judged)")
        if not self.verdicts:
            raise ValueError(f"{self.task_id}: a gold label with no verdicts records nothing")
        for rule, verdict in self.verdicts.items():
            if verdict not in VERDICTS:
                raise ValueError(
                    f"{self.task_id}: verdict for rule {rule!r} is {verdict!r}; "
                    f"must be one of {sorted(VERDICTS)}"
                )

    def scorable(self) -> dict[str, str]:
        """Verdicts usable for agreement scoring (``unclear`` dropped)."""
        return {r: v for r, v in self.verdicts.items() if v in SCORABLE_VERDICTS}


def gold_label_from_dict(data: dict[str, Any]) -> GoldLabel:
    """Build a :class:`GoldLabel` from its JSON dict shape.

    Raises ``KeyError``/``ValueError`` on a malformed record rather than
    filling in defaults — a silently-defaulted gold label is a fabricated
    one.
    """
    verdicts = data["verdicts"]
    if not isinstance(verdicts, dict):
        raise ValueError(
            f"{data.get('task_id')!r}: 'verdicts' must be an object of rule -> verdict"
        )
    return GoldLabel(
        task_id=data["task_id"],
        labeled_by=data["labeled_by"],
        labeled_at=data["labeled_at"],
        verdicts=dict(verdicts),
        notes=data.get("notes"),
    )


def load_gold_label(path: Path) -> GoldLabel:
    """Load a single gold-label JSON file."""
    with open(path, encoding="utf-8") as f:
        return gold_label_from_dict(json.load(f))


def load_gold_set(directory: Path) -> list[GoldLabel]:
    """Load every ``*.json`` gold label in ``directory``, sorted by task_id.

    Returns an empty list for a directory with no label files — which is the
    honest answer while the gold set is still being built, and is why
    ``agreement.py`` must handle an empty reference set explicitly rather
    than dividing by zero.
    """
    labels = [load_gold_label(p) for p in _label_files(directory)]
    duplicates = _duplicate_task_ids(labels)
    if duplicates:
        raise ValueError(
            f"duplicate task_id(s) in gold set {directory}: {sorted(duplicates)}; "
            "two labels for the same trajectory would be double-counted in agreement"
        )
    return sorted(labels, key=lambda label: label.task_id)


def _label_files(directory: Path) -> Iterator[Path]:
    return iter(sorted(p for p in directory.glob("*.json") if p.is_file()))


def _duplicate_task_ids(labels: list[GoldLabel]) -> set[str]:
    seen: set[str] = set()
    dupes: set[str] = set()
    for label in labels:
        if label.task_id in seen:
            dupes.add(label.task_id)
        seen.add(label.task_id)
    return dupes
